import fs from "fs";

const API_URL = "https://admin.starwarsunlimited.com/api/card-list";
const OUTPUT_PATH = "src/lib/card-images.ts";

const headers = {
  Accept: "application/json",
  Origin: "https://starwarsunlimited.com",
  Referer: "https://starwarsunlimited.com/",
};

async function fetchLeaders() {
  const allCards = [];
  let page = 1;

  while (true) {
    const params = new URLSearchParams({
      locale: "en",
      "pagination[page]": String(page),
      "pagination[pageSize]": "100",
      populate: "*",
      "filters[type][name][$eq]": "Leader",
      "filters[variantOf][id][$null]": "true",
    });

    const res = await fetch(`${API_URL}?${params}`, { headers });
    if (!res.ok) throw new Error(`API error: ${res.status}`);
    const data = await res.json();

    allCards.push(...data.data);
    const { pageCount } = data.meta.pagination;
    console.log(`Fetched page ${page}/${pageCount} (${data.data.length} cards)`);

    if (page >= pageCount) break;
    page++;
  }

  return allCards;
}

function extractImageUrl(card) {
  const art = card.attributes?.artFront?.data?.attributes;
  if (!art) return null;
  return art.formats?.card?.url || art.url || null;
}

function buildLeaderKey(card) {
  const title = card.attributes?.title;
  const subtitle = card.attributes?.subtitle;
  if (!title) return null;
  return subtitle ? `${title}, ${subtitle}` : title;
}

async function main() {
  console.log("Fetching leader cards from SWU API...");
  const cards = await fetchLeaders();
  console.log(`Found ${cards.length} leader cards`);

  const mapping = {};
  for (const card of cards) {
    const key = buildLeaderKey(card);
    const url = extractImageUrl(card);
    if (key && url) {
      mapping[key] = url;
    }
  }

  const sorted = Object.entries(mapping).sort(([a], [b]) => a.localeCompare(b));

  const lines = [
    `// Auto-generated by scripts/generate-card-images.mjs`,
    `// Run: node scripts/generate-card-images.mjs`,
    ``,
    `export const LEADER_IMAGES: Record<string, string> = {`,
  ];

  for (const [name, url] of sorted) {
    lines.push(`  ${JSON.stringify(name)}: ${JSON.stringify(url)},`);
  }

  lines.push(`};`);
  lines.push(``);
  lines.push(`export function getLeaderImageUrl(leaderName: string): string | null {`);
  lines.push(`  return LEADER_IMAGES[leaderName] ?? null;`);
  lines.push(`}`);
  lines.push(``);

  fs.writeFileSync(OUTPUT_PATH, lines.join("\n"));
  console.log(`Wrote ${sorted.length} leaders to ${OUTPUT_PATH}`);
}

main().catch(console.error);
