import fs from "fs";

const API_URL = "https://admin.starwarsunlimited.com/api/card-list";
const OUTPUT_PATH = "src/lib/card-images.ts";

const headers = {
  Accept: "application/json",
  Origin: "https://starwarsunlimited.com",
  Referer: "https://starwarsunlimited.com/",
};

async function fetchLeaders() {
  const allCards = [];
  let page = 1;

  while (true) {
    const params = new URLSearchParams({
      locale: "en",
      "pagination[page]": String(page),
      "pagination[pageSize]": "100",
      populate: "*",
      "filters[type][name][$eq]": "Leader",
      "filters[variantOf][id][$null]": "true",
    });

    const res = await fetch(`${API_URL}?${params}`, { headers });
    if (!res.ok) throw new Error(`API error: ${res.status}`);
    const data = await res.json();

    allCards.push(...data.data);
    const { pageCount } = data.meta.pagination;
    console.log(`Fetched page ${page}/${pageCount} (${data.data.length} cards)`);

    if (page >= pageCount) break;
    page++;
  }

  return allCards;
}

function extractImageUrl(card) {
  const art = card.attributes?.artFront?.data?.attributes;
  if (!art) return null;
  return art.formats?.card?.url || art.url || null;
}

function extractThumbnailUrl(card) {
  const art = card.attributes?.artThumbnail?.data?.attributes;
  if (!art) return null;
  return art.formats?.thumbnail?.url || art.url || null;
}

function extractSetCode(card) {
  return card.attributes?.expansion?.data?.attributes?.code ?? null;
}

function extractAspects(card) {
  const data = card.attributes?.aspects?.data;
  if (!Array.isArray(data)) return [];
  return data.map(a => a.attributes?.name).filter(Boolean);
}

function buildLeaderKey(card) {
  const title = card.attributes?.title;
  const subtitle = card.attributes?.subtitle;
  if (!title) return null;
  return subtitle ? `${title}, ${subtitle}` : title;
}

async function main() {
  console.log("Fetching leader cards from SWU API...");
  const cards = await fetchLeaders();
  console.log(`Found ${cards.length} leader cards`);

  const cards_map = {};
  const thumbs = {};
  const sets = {};
  const aspects = {};
  for (const card of cards) {
    const key = buildLeaderKey(card);
    if (!key) continue;
    const url = extractImageUrl(card);
    const thumb = extractThumbnailUrl(card);
    const setCode = extractSetCode(card);
    const cardAspects = extractAspects(card);
    if (url) cards_map[key] = url;
    if (thumb) thumbs[key] = thumb;
    if (setCode) sets[key] = setCode;
    if (cardAspects.length > 0) aspects[key] = cardAspects;
  }

  const allKeys = [...new Set([...Object.keys(cards_map), ...Object.keys(thumbs)])].sort();

  const lines = [
    `// Auto-generated by scripts/generate-card-images.mjs`,
    `// Run: node scripts/generate-card-images.mjs`,
    ``,
    `export const LEADER_IMAGES: Record<string, string> = {`,
  ];
  for (const name of allKeys) {
    if (cards_map[name]) lines.push(`  ${JSON.stringify(name)}: ${JSON.stringify(cards_map[name])},`);
  }
  lines.push(`};`);

  lines.push(``);
  lines.push(`export const LEADER_THUMBNAILS: Record<string, string> = {`);
  for (const name of allKeys) {
    if (thumbs[name]) lines.push(`  ${JSON.stringify(name)}: ${JSON.stringify(thumbs[name])},`);
  }
  lines.push(`};`);

  lines.push(``);
  lines.push(`export const LEADER_SETS: Record<string, string> = {`);
  for (const name of allKeys) {
    if (sets[name]) lines.push(`  ${JSON.stringify(name)}: ${JSON.stringify(sets[name])},`);
  }
  lines.push(`};`);

  lines.push(``);
  lines.push(`export const LEADER_ASPECTS: Record<string, string[]> = {`);
  for (const name of allKeys) {
    if (aspects[name]) lines.push(`  ${JSON.stringify(name)}: ${JSON.stringify(aspects[name])},`);
  }
  lines.push(`};`);

  lines.push(``);
  lines.push(`export function getLeaderImageUrl(leaderName: string): string | null {`);
  lines.push(`  return LEADER_IMAGES[leaderName] ?? null;`);
  lines.push(`}`);
  lines.push(``);
  lines.push(`export function getLeaderThumbnailUrl(leaderName: string): string | null {`);
  lines.push(`  return LEADER_THUMBNAILS[leaderName] ?? null;`);
  lines.push(`}`);
  lines.push(``);
  lines.push(`export function getLeaderSetCode(leaderName: string): string | null {`);
  lines.push(`  return LEADER_SETS[leaderName] ?? null;`);
  lines.push(`}`);
  lines.push(``);
  lines.push(`export function getLeaderAspects(leaderName: string): string[] {`);
  lines.push(`  return LEADER_ASPECTS[leaderName] ?? [];`);
  lines.push(`}`);
  lines.push(``);

  fs.writeFileSync(OUTPUT_PATH, lines.join("\n"));
  console.log(`Wrote ${allKeys.length} leaders to ${OUTPUT_PATH}`);
}

main().catch(console.error);
