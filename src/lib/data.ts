export function getPlayerTier(player: Player, rank: number) {
  if (rank === 1) {
    return { name: "The Chosen One", isChosenOne: true };
  }
  const faction = factions[player.faction];
  const tier = faction.tiers.find((t) => player.midichlorianIndex >= t.minRating) ?? faction.tiers[faction.tiers.length - 1];
  return { name: tier.name, isChosenOne: false };
}

export function getFactionSide(faction: Faction) {
  return factions[faction].side;
}

