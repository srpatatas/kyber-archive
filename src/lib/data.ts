export function getWinRate(player: Player): number {
  const total = player.wins + player.losses + player.draws;
  if (total === 0) return 0;
  return Math.round((player.wins / total) * 1000) / 10;
}

export function getTotalGames(player: Player): number {
  return player.wins + player.losses + player.draws;
}

